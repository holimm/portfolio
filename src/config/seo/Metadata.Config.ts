'use server';
import { type Metadata } from 'next';

/** The live site. `NEXT_PUBLIC_WEBSITE_SITE_URL` can override it, e.g. for a staging domain. */
const SITE_URL =
  process.env.NEXT_PUBLIC_WEBSITE_SITE_URL || 'https://www.holim.dev/';

export async function generatePageMetadata(): Promise<Metadata> {
  const siteName = 'Portfolio';
  const siteSlogan = 'Ho Chi Minh City';
  const siteDescription =
    'Ho Lim - A passionate frontend developer based in Ho Chi Minh City, Vietnam. Specializing in crafting engaging and user-friendly web experiences.';
  const titleSeparator = '·';

  const metadataTitle = `${siteName} ${titleSeparator} ${siteSlogan}`;
  const metadataDescription = siteDescription;

  const isProduction =
    process.env.NEXT_PUBLIC_ENVIRONMENT === 'production' ||
    // Server-side and always set on Vercel; the NEXT_PUBLIC_ copy depends on a project setting
    process.env.VERCEL_ENV === 'production' ||
    process.env.NEXT_PUBLIC_VERCEL_ENV === 'production';

  return {
    // Resolves relative Open Graph and Twitter image URLs against the live domain
    metadataBase: new URL(SITE_URL),
    title: {
      default: metadataTitle,
      template: `%s ${titleSeparator} ${siteName} ${titleSeparator} ${siteSlogan}`,
    },
    description: metadataDescription,
    keywords: ['Portfolio'],
    referrer: 'origin-when-cross-origin',
    openGraph: {
      title: metadataTitle,
      description: metadataDescription,
      url: SITE_URL,
      // The image comes from src/app/opengraph-image.png (generated by `yarn icons`)
    },
    twitter: {
      title: metadataTitle,
      description: metadataDescription,
      // X falls back to the Open Graph image when no twitter:image is set
      card: 'summary_large_image',
    },
    // Favicons, the Apple touch icon and the manifest come from files in src/app (see `yarn icons`)
    robots: {
      // Only the production site is indexed; previews and local builds stay out of search results
      index: isProduction,
      follow: isProduction,
      googleBot: {
        index: isProduction,
        follow: isProduction,
      },
    },
    alternates: {
      canonical: SITE_URL,
    },
    other: {
      'theme-color': '#ffffff',
      'msapplication-TileColor': '#ffffff',
      'build:env':
        process.env.NEXT_PUBLIC_ENVIRONMENT ||
        process.env.NEXT_PUBLIC_VERCEL_ENV ||
        'NO_ENV',
      'build:version':
        process.env.NEXT_PUBLIC_VERCEL_GIT_REPO_ID || 'NO_GIT_REPO_ID',
      'build:version:commit':
        process.env.NEXT_PUBLIC_COMMIT_SHA || 'NO_GIT_COMMIT_SHA',
      'build:commit:auth':
        process.env.NEXT_PUBLIC_VERCEL_GIT_COMMIT_AUTHOR_NAME ||
        'NO_AUTHOR_NAME',
    },
  };
}
